function hashString(input: string): number {
  let hash = 0;
  for (let i = 0; i < input.length; i++) {
    hash = (hash * 31 + input.charCodeAt(i)) | 0;
  }
  return Math.abs(hash);
}

export function pickArtwork(seed: string, categories?: ArtCategory[]): Artwork {
  const pool = categories?.length
    ? ARTWORKS.filter((a) => a.categories.some((c) => categories.includes(c)))
    : ARTWORKS;
  const list = pool.length ? pool : ARTWORKS;
  return list[hashString(seed) % list.length];
}

export function commonsImageUrl(artwork: Artwork, width = 1400): string {
  const path = encodeURIComponent(artwork.commonsFile.replace(/ /g, "_"));
  return `https://commons.wikimedia.org/wiki/Special:FilePath/${path}?width=${width}`;
}

// Local filenames downloaded by scripts/fetch-artwork-images.mjs at build
// time, keyed by artwork id. Empty until that script has run (e.g. in local
// dev without the build step), in which case artworkImageUrl() below falls
// back to the live Commons URL.
const localFiles = artworkFiles as Record<string, string>;

/** Prefers the locally bundled copy (no flicker, no live Commons dependency); falls back to Commons if not yet downloaded. */
export function artworkImageUrl(artwork: Artwork, width = 1400): string {
  const local = localFiles[artwork.id];
  return local ? `${import.meta.env.BASE_URL}artworks/${local}` : commonsImageUrl(artwork, width);
}
